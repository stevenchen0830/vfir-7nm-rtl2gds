#!/usr/bin/env python3
"""Deterministically splice a MAC candidate into the immutable v4 top."""
import argparse
import hashlib
import json
from pathlib import Path

BASE_SHA256 = 'b1ffeaf5fccad2442519b58076420b3a723d9c800e29ad7f26974ca817566283'
REPO = Path(__file__).resolve().parents[2]


def generate():
    data = (REPO/'rtl/img_filter.v').read_bytes()
    if hashlib.sha256(data).hexdigest() != BASE_SHA256:
        raise ValueError('v4 source hash changed: review the splice before using this candidate')
    text = data.decode('utf-8')
    start = text.index('    // Stage 1 (valid at out_d2):')
    end = text.index('    //========================================================================\n    // 8.', start)
    replacement = '''    // v5 experiment: eight registered MAC stages plus the output register.
    // Extra six enabled-cycle latency versus v4; bank protocol is unchanged.
    wire [159:0] result;
    wire mac_valid;
    fir_mac_pipeline u_mac (
        .clk(clk), .rst_n(rst_n), .advance(pipe_en), .in_valid(out_d2),
        .tap_data(tapd), .tap_coef(tapc), .out_valid(mac_valid), .result(result)
    );

'''
    text = text[:start] + replacement + text[end:]
    assert text.count('wire opush = pipe_en & out_d4;') == 1
    text = text.replace('wire opush = pipe_en & out_d4;', 'wire opush = pipe_en & mac_valid;')
    text = text.replace('out_d1, out_d2, out_d3, out_d4;', 'out_d1, out_d2;')
    for line in ['            out_d3 <= 1\'b0;\n', '            out_d4 <= 1\'b0;\n',
                 '            out_d3 <= out_d2;\n', '            out_d4 <= out_d3;\n']:
        assert text.count(line) == 1
        text = text.replace(line, '')
    text = text.replace('//  Timing     : accept -> mem -> rdata -> MAC1 -> MAC2 -> MAC3 -> out (6 cyc),',
                        '//  Timing     : v5 experiment adds six enabled cycles to the v4 MAC path,')
    return ('// GENERATED by experiments/fir_pipeline/build_variant.py; do not edit.\n'+text).encode()


def main():
    p=argparse.ArgumentParser()
    p.add_argument('output', type=Path)
    a=p.parse_args()
    payload=generate()
    a.output.mkdir(parents=True, exist_ok=True)
    target=a.output/'img_filter.v'
    if target.exists() and target.read_bytes()!=payload:
        p.error('Existing generated RTL differs; use a fresh directory')
    target.write_bytes(payload)
    hashes={str(f.relative_to(REPO)):hashlib.sha256(f.read_bytes()).hexdigest() for f in
            [REPO/'rtl/img_filter.v', Path(__file__), REPO/'experiments/fir_pipeline/rtl/fir_mac_pipeline.v']}
    manifest={'baseline':'v4', 'candidate':'v5_split_multiply_binary_reduction',
              'inputs':hashes, 'generated_sha256':hashlib.sha256(payload).hexdigest(),
              'extra_enabled_cycles':6, 'physical_status':'NOT_RUN'}
    (a.output/'source-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(target)


if __name__=='__main__': main()
